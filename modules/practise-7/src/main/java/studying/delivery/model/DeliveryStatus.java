package studying.delivery.model;

/** Состояние доставки, независимое от результата отдельной попытки. */
public enum DeliveryStatus {
    /** Доставка ожидает первую или повторную попытку. */
    PENDING,
    /** Доставка успешно завершена. */
    SUCCEEDED,
    /** Доставка завершена с ошибкой без дальнейших повторов. */
    FAILED
}
